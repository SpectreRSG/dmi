-- Payroll tax payments the office made to the IRS and the EDD, recorded in
-- DMI so it can show what's paid, what's due and what's late (Pay → Tax payments).
CREATE TABLE tax_deposits (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind        TEXT NOT NULL CHECK (kind IN ('federal', 'california', 'futa', 'ca_ui')),
  period_key  TEXT NOT NULL,  -- which payment it was for: 'M:2026-10' (a month), 'S:2026-10-23' (semiweekly), 'Q:2026-4' (a quarter)
  paid_on     TEXT NOT NULL,
  amount      DOUBLE PRECISION NOT NULL CHECK (amount > 0),
  reference   TEXT,           -- the EFTPS or EDD confirmation number
  recorded_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at  TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX tax_deposits_period ON tax_deposits (kind, period_key);
