-- Use of force and incident reports. An officer fills one in (the same
-- questions as the California PPO incident record in assets/), signs it and
-- sends it to the admins, who review it and approve it or ask for more
-- information. Once sent, the officer's account is never changed: anything
-- new goes in a dated supplement. Reports are kept for 5 years after the
-- incident (longer if put on legal hold); the database itself refuses to
-- delete one sooner.
CREATE TABLE incident_reports (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number         TEXT UNIQUE,                 -- e.g. IR-2026-0007
  employee_id    INTEGER NOT NULL REFERENCES employees(id), -- the reporting officer (a staff record with reports can't be deleted)
  created_by     INTEGER REFERENCES users(id) ON DELETE SET NULL,
  shift_id       INTEGER REFERENCES shifts(id) ON DELETE SET NULL,
  site_id        INTEGER REFERENCES sites(id),
  incident_date  TEXT,                        -- '2026-10-20'
  incident_start TEXT,                        -- '22:15'
  types          TEXT,                        -- what kind of incident, e.g. 'type_force,type_injury'
  status         TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'info_requested', 'approved')),
  data           JSONB NOT NULL DEFAULT '{}', -- the officer's answers, by the form's field names
  review         JSONB NOT NULL DEFAULT '{}', -- the admins' review (page 7 of the form)
  submitted_at   TEXT,
  signed_name    TEXT,                        -- the name the officer typed as their signature
  signed_ip      TEXT,
  approved_by    INTEGER REFERENCES users(id) ON DELETE SET NULL,
  approved_at    TEXT,
  retain_until   TEXT,                        -- may not be deleted before this date
  legal_hold     INTEGER NOT NULL DEFAULT 0,  -- 1 = keep even after retain_until
  updated_ms     BIGINT NOT NULL DEFAULT 0,   -- when the draft was last saved (for the phone's backup copy)
  created_at     TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX incident_reports_employee ON incident_reports (employee_id, created_at);
CREATE INDEX incident_reports_status ON incident_reports (status, incident_date);

-- Everything that happens to a report, oldest first: sent, more information
-- asked for, supplements (the officer's dated additions), approved, files added.
CREATE TABLE incident_report_events (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id  INTEGER NOT NULL REFERENCES incident_reports(id) ON DELETE CASCADE,
  user_id    INTEGER REFERENCES users(id) ON DELETE SET NULL,
  user_name  TEXT,
  kind       TEXT NOT NULL,
  note       TEXT,
  created_at TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX incident_report_events_report ON incident_report_events (report_id, id);

-- Photos and documents attached to a report (stored like other uploads).
CREATE TABLE incident_report_files (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id     INTEGER NOT NULL REFERENCES incident_reports(id) ON DELETE CASCADE,
  file_name     TEXT NOT NULL,
  file_original TEXT NOT NULL,
  note          TEXT,
  uploaded_by   INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at    TEXT NOT NULL DEFAULT app_now()
);

-- Once sent, the officer's account and signature can't be changed, and the
-- report can't be deleted until its 5 years are up (or while on legal hold).
CREATE FUNCTION incident_reports_protect() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status <> 'draft' AND (OLD.legal_hold = 1 OR OLD.retain_until IS NULL OR OLD.retain_until > left(app_now(), 10)) THEN
      RAISE EXCEPTION 'Incident report % must be kept until %', OLD.number, COALESCE(OLD.retain_until, 'it is approved');
    END IF;
    RETURN OLD;
  END IF;
  IF OLD.status <> 'draft' AND (
    NEW.data IS DISTINCT FROM OLD.data OR NEW.employee_id IS DISTINCT FROM OLD.employee_id
    OR NEW.signed_name IS DISTINCT FROM OLD.signed_name OR NEW.submitted_at IS DISTINCT FROM OLD.submitted_at
    OR NEW.number IS DISTINCT FROM OLD.number OR NEW.incident_date IS DISTINCT FROM OLD.incident_date
    OR NEW.status = 'draft'
  ) THEN
    RAISE EXCEPTION 'Incident report % was sent: add a supplement instead of changing it', OLD.number;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER incident_reports_protect BEFORE UPDATE OR DELETE ON incident_reports
  FOR EACH ROW EXECUTE FUNCTION incident_reports_protect();
