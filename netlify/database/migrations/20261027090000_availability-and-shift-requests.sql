-- Officers say when they can't work (or would like extra shifts), and site
-- representatives (client accounts) request shifts, which the office approves.

-- When an officer is unavailable, or available for extra shifts. Either a
-- date range (one day if end_date is the same), or a weekly repeat
-- ("every Tuesday") from start_date until end_date (empty: no end).
CREATE TABLE availability (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  kind        TEXT NOT NULL CHECK (kind IN ('unavailable', 'available')),
  start_date  TEXT NOT NULL,
  end_date    TEXT,
  weekdays    TEXT,  -- weekly repeat: days like '0,2' (0 = Monday … 6 = Sunday); empty = every day in the range
  start_time  TEXT,  -- empty = all day; an end earlier than the start finishes the next day
  end_time    TEXT,
  note        TEXT,
  created_at  TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX availability_employee ON availability (employee_id);

-- A shift a site representative asked for. The office approves it (the
-- shifts are made and offered to officers) or declines it.
CREATE TABLE shift_requests (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id       INTEGER NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  site_id         INTEGER NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
  requested_by    INTEGER REFERENCES users(id) ON DELETE SET NULL,
  start_at        TEXT NOT NULL,
  end_at          TEXT NOT NULL,
  break_minutes   INTEGER NOT NULL DEFAULT 0,
  officers_needed INTEGER NOT NULL DEFAULT 1 CHECK (officers_needed BETWEEN 1 AND 10),
  notes           TEXT,
  status          TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'declined', 'cancelled')),
  decided_by      INTEGER REFERENCES users(id) ON DELETE SET NULL,
  decided_at      TEXT,
  decline_reason  TEXT,
  created_at      TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX shift_requests_status ON shift_requests (status, start_at);
CREATE INDEX shift_requests_client ON shift_requests (client_id, start_at);

-- Officers the site asked for by name: they get first choice.
CREATE TABLE shift_request_officers (
  request_id  INTEGER NOT NULL REFERENCES shift_requests(id) ON DELETE CASCADE,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  PRIMARY KEY (request_id, employee_id)
);

-- Shifts made from an approved request remember it, so the site hears when they're covered.
ALTER TABLE shifts ADD COLUMN request_id INTEGER REFERENCES shift_requests(id) ON DELETE SET NULL;
