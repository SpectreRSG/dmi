-- Two-step sign-in: after the password, a 6-digit code from an authenticator
-- app on the person's phone (Google Authenticator, Microsoft Authenticator,
-- 1Password...). Someone who steals a password still can't get in.

-- The app's secret key for each person, stored scrambled (encrypted). Empty
-- until they set it up.
ALTER TABLE users ADD COLUMN totp_secret TEXT;
ALTER TABLE users ADD COLUMN totp_enabled_at TEXT;
-- The last 30-second code that was used, so the same code can't be used twice.
ALTER TABLE users ADD COLUMN totp_last_step BIGINT;

-- One-time backup codes, for when someone doesn't have their phone. Only a
-- scrambled (hashed) copy is kept; each one works once.
CREATE TABLE recovery_codes (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code_hash TEXT NOT NULL,
  used_at   TEXT
);
CREATE INDEX recovery_codes_user ON recovery_codes (user_id);

-- "Remember this device for 30 days": skips the code (never the password) on
-- that phone or computer. Only a hash of the device's token is kept.
CREATE TABLE trusted_devices (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash   TEXT NOT NULL UNIQUE,
  device       TEXT,
  expires_at   BIGINT NOT NULL, -- milliseconds
  created_at   TEXT NOT NULL DEFAULT app_now(),
  last_used_at TEXT
);
CREATE INDEX trusted_devices_user ON trusted_devices (user_id);

-- Who must use two-step sign-in: 'everyone' (the default) or 'office'
-- (admins and managers only). Changed on the Settings page.
INSERT INTO settings (key, value) VALUES ('two_step_required_for', 'everyone') ON CONFLICT (key) DO NOTHING;
