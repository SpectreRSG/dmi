-- Passkeys: signing in with Face ID, Touch ID, a fingerprint or the device's
-- PIN instead of a password and code. The phone (or computer) keeps a secret
-- key that never leaves it; this table only keeps the matching public key,
-- which can check a sign-in but can't be used to make one.
CREATE TABLE passkeys (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  credential_id TEXT NOT NULL UNIQUE, -- the passkey's id, as the device reports it
  public_key    TEXT NOT NULL,        -- the public key (SPKI, base64url)
  algorithm     INTEGER NOT NULL,     -- -7 = ES256 (iPhones, most devices), -257 = RS256, -8 = Ed25519
  sign_count    BIGINT NOT NULL DEFAULT 0,
  rp_id         TEXT NOT NULL,        -- the website it belongs to, e.g. dmi.codehound.org
  name          TEXT,                 -- e.g. "Safari on iPhone"
  created_at    TEXT NOT NULL DEFAULT app_now(),
  last_used_at  TEXT
);
CREATE INDEX passkeys_user ON passkeys (user_id);
