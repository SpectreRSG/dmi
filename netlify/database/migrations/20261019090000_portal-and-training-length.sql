-- Passphrases for the public schedule portal (/portal). Each one shows the
-- schedule of one officer, one site, or every site of one client. Only a
-- keyed hash of the passphrase is stored, never the passphrase itself.
CREATE TABLE portal_access (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope           TEXT NOT NULL CHECK (scope IN ('employee', 'site', 'client')),
  employee_id     INTEGER REFERENCES employees(id) ON DELETE CASCADE,
  site_id         INTEGER REFERENCES sites(id) ON DELETE CASCADE,
  client_id       INTEGER REFERENCES clients(id) ON DELETE CASCADE,
  label           TEXT,
  passphrase_hash TEXT NOT NULL UNIQUE,
  expires_on      TEXT,
  last_used_at    TEXT,
  created_by      INTEGER REFERENCES users(id),
  created_at      TEXT NOT NULL DEFAULT app_now()
);

-- How long a training session lasts, so it can be checked against shifts.
ALTER TABLE training_sessions ADD COLUMN duration_minutes INTEGER NOT NULL DEFAULT 240;
