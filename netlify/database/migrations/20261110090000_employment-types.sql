-- Employment types decide how someone is paid and taxed (services/employment.js):
--   Full Time          W-2 employee, paid hourly or a salary (a salary can be exempt from overtime)
--   Part Time Regular  W-2 employee, a set salary for a regular part-time schedule
--   Part Time Hourly   W-2 employee, paid for the hours worked
--   Contractor         1099 independent contractor, the agreed rate for every hour
ALTER TABLE employees ADD COLUMN pay_basis TEXT NOT NULL DEFAULT 'hourly' CHECK (pay_basis IN ('hourly', 'salary'));
ALTER TABLE employees ADD COLUMN annual_salary DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (annual_salary >= 0);
ALTER TABLE employees ADD COLUMN weekly_hours DOUBLE PRECISION NOT NULL DEFAULT 40 CHECK (weekly_hours > 0 AND weekly_hours <= 40); -- the hours a salary is for
ALTER TABLE employees ADD COLUMN overtime_exempt INTEGER NOT NULL DEFAULT 0;
-- The day a contractor became an employee (for the new hire report and sick leave).
ALTER TABLE employees ADD COLUMN w2_since TEXT;
-- Meal breaks: the day the person signed a written on-duty meal agreement (they
-- eat at their post, paid), and the day they agreed to skip the meal break on
-- short days (6 hours or less) and the second one on days of 12 hours or less.
ALTER TABLE employees ADD COLUMN meal_agreement_on TEXT;
ALTER TABLE employees ADD COLUMN meal_waiver_on TEXT;

-- Today's types, mapped to the new ones so everyone is paid exactly as before:
-- 1099s become Contractors, W-2s Full Time or Part Time Hourly (still hourly).
UPDATE employees SET employment_type = CASE
  WHEN tax_form = '1099' THEN 'Contractor'
  WHEN employment_type IN ('Part-time', 'Casual', 'Contractor') THEN 'Part Time Hourly'
  ELSE 'Full Time' END;
ALTER TABLE employees ALTER COLUMN employment_type SET DEFAULT 'Contractor';
ALTER TABLE employees ALTER COLUMN employment_type SET NOT NULL;
ALTER TABLE employees ADD CONSTRAINT employees_employment_type_check
  CHECK (employment_type IN ('Full Time', 'Part Time Regular', 'Part Time Hourly', 'Contractor'));
-- The type and the rest always agree.
ALTER TABLE employees ADD CONSTRAINT employees_type_tax_form_check CHECK ((employment_type = 'Contractor') = (tax_form = '1099'));
ALTER TABLE employees ADD CONSTRAINT employees_type_pay_basis_check CHECK (
  pay_basis = CASE employment_type WHEN 'Part Time Regular' THEN 'salary' WHEN 'Full Time' THEN pay_basis ELSE 'hourly' END
);
ALTER TABLE employees ADD CONSTRAINT employees_exempt_check CHECK (overtime_exempt = 0 OR (employment_type = 'Full Time' AND pay_basis = 'salary'));

-- Every change to how someone is paid: what it was, what it became, who changed it.
CREATE TABLE employment_changes (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  changed_on  TEXT NOT NULL,
  before      JSONB NOT NULL,
  after       JSONB NOT NULL,
  changed_by  INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at  TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX employment_changes_employee ON employment_changes (employee_id, id);

