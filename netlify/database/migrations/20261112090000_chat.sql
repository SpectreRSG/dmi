-- Messages between each officer or client and the office (the admins): one
-- private conversation per person, which every admin can read and answer.
-- Every message is date and time stamped, can't be changed, and is kept for
-- 2 years; after that the nightly jobs remove it (services/chat.js).
CREATE TABLE chat_threads (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         INTEGER UNIQUE REFERENCES users(id) ON DELETE SET NULL, -- the officer's or client's account
  person_name     TEXT NOT NULL,             -- kept with the conversation, in case the account changes
  person_role     TEXT NOT NULL,             -- 'officer' or 'client' when it started
  last_message_at TEXT,
  created_at      TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX chat_threads_recent ON chat_threads (last_message_at);

CREATE TABLE chat_messages (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id   INTEGER NOT NULL REFERENCES chat_threads(id) ON DELETE CASCADE,
  sender_id   INTEGER REFERENCES users(id) ON DELETE SET NULL,
  sender_name TEXT NOT NULL,
  sender_role TEXT NOT NULL,                 -- 'admin', 'officer' or 'client'
  body        TEXT NOT NULL CHECK (length(body) BETWEEN 1 AND 2000),
  created_at  TEXT NOT NULL DEFAULT app_now() -- company time, 'YYYY-MM-DD HH:MM:SS'
);
CREATE INDEX chat_messages_thread ON chat_messages (thread_id, id);
CREATE INDEX chat_messages_age ON chat_messages (created_at);

-- How far each person has read in each conversation (for unread counts).
CREATE TABLE chat_reads (
  thread_id    INTEGER NOT NULL REFERENCES chat_threads(id) ON DELETE CASCADE,
  user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  last_read_id INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (thread_id, user_id)
);

-- A sent message is never changed, and can't be deleted until it's 2 years old.
CREATE FUNCTION chat_messages_protect() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.created_at > to_char(app_now()::timestamp - interval '2 years', 'YYYY-MM-DD HH24:MI:SS') THEN
      RAISE EXCEPTION 'Chat messages are kept for 2 years (this one is from %)', OLD.created_at;
    END IF;
    RETURN OLD;
  END IF;
  IF NEW.body IS DISTINCT FROM OLD.body OR NEW.created_at IS DISTINCT FROM OLD.created_at
    OR NEW.thread_id IS DISTINCT FROM OLD.thread_id OR NEW.sender_name IS DISTINCT FROM OLD.sender_name THEN
    RAISE EXCEPTION 'Chat messages can''t be changed once sent';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER chat_messages_protect BEFORE UPDATE OR DELETE ON chat_messages
  FOR EACH ROW EXECUTE FUNCTION chat_messages_protect();
