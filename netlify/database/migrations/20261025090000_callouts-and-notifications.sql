-- App notifications (free "push" messages to phones and computers), call-outs,
-- and open shifts that the first eligible officer to claim gets.

-- A phone or computer that agreed to get notifications for someone's account.
-- The browser gives us these three values; we never see anything else.
CREATE TABLE push_subscriptions (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  endpoint     TEXT NOT NULL UNIQUE, -- the address the notification is sent to
  p256dh       TEXT NOT NULL,        -- keys that scramble the message so only that device can read it
  auth         TEXT NOT NULL,
  device       TEXT,                 -- e.g. "iPhone", to tell them apart
  created_at   TEXT NOT NULL DEFAULT app_now(),
  last_sent_at TEXT
);
CREATE INDEX push_subscriptions_user ON push_subscriptions (user_id);

-- Someone saying they can't work a shift (told by the officer, or noted by the office).
CREATE TABLE shift_callouts (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_id     INTEGER REFERENCES shifts(id) ON DELETE SET NULL,
  employee_id  INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  reason       TEXT,
  reported_by  INTEGER REFERENCES users(id) ON DELETE SET NULL,
  hours_notice DOUBLE PRECISION NOT NULL, -- how long before the shift started
  shift_start  TEXT NOT NULL,             -- kept in case the shift is deleted later
  created_at   TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX shift_callouts_employee ON shift_callouts (employee_id, created_at);

-- An unfilled shift offered to officers. They're told in waves (regulars at
-- that site first); the first eligible officer to claim it gets it. If nobody
-- has by escalate_at, the office is told.
-- Times like '2026-10-20T14:30', in the company's time zone.
CREATE TABLE shift_offers (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_id     INTEGER NOT NULL REFERENCES shifts(id) ON DELETE CASCADE,
  status       TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'filled', 'withdrawn')),
  created_by   INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at   TEXT NOT NULL DEFAULT app_now(),
  next_wave_at TEXT, -- when the next group is told (empty once everyone has been)
  escalate_at  TEXT NOT NULL,
  escalated_at TEXT,
  filled_by    INTEGER REFERENCES employees(id) ON DELETE SET NULL,
  filled_at    TEXT,
  closed_note  TEXT
);
CREATE UNIQUE INDEX shift_offers_one_open ON shift_offers (shift_id) WHERE status = 'open';
CREATE INDEX shift_offers_status ON shift_offers (status);

-- Who each offer goes to, in which wave, and when they were told.
CREATE TABLE shift_offer_recipients (
  offer_id    INTEGER NOT NULL REFERENCES shift_offers(id) ON DELETE CASCADE,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  wave        INTEGER NOT NULL,
  notified_at TEXT,
  PRIMARY KEY (offer_id, employee_id)
);
