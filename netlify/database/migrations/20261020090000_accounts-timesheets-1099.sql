-- Accounts for everyone (officers and clients too), officer timesheet
-- submissions, and what's needed for 1099-NEC forms.

-- Anyone can sign up. A new account is "pending" until an admin gives it a role.
-- Officers are linked to their staff record, clients to their client record.
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('admin', 'manager', 'officer', 'client', 'pending'));
ALTER TABLE users ADD COLUMN phone TEXT;
ALTER TABLE users ADD COLUMN requested_role TEXT; -- what they said they were when signing up
ALTER TABLE users ADD COLUMN employee_id INTEGER REFERENCES employees(id) ON DELETE SET NULL;
ALTER TABLE users ADD COLUMN client_id INTEGER REFERENCES clients(id) ON DELETE SET NULL;
CREATE UNIQUE INDEX users_employee_unique ON users (employee_id) WHERE employee_id IS NOT NULL;

-- The passphrase portal is replaced by accounts.
DROP TABLE IF EXISTS portal_access;

-- How each person is paid: 1099-NEC (independent contractor) or W-2 (employee).
ALTER TABLE employees ADD COLUMN tax_form TEXT NOT NULL DEFAULT '1099' CHECK (tax_form IN ('1099', 'W-2'));

-- A two-week timesheet an officer submitted, with the filled-in DMI PDF.
CREATE TABLE timesheet_submissions (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id  INTEGER NOT NULL REFERENCES employees(id),
  user_id      INTEGER REFERENCES users(id) ON DELETE SET NULL,
  period_start TEXT NOT NULL,
  period_end   TEXT NOT NULL,
  location     TEXT,
  phone        TEXT,
  total_hours  DOUBLE PRECISION NOT NULL DEFAULT 0,
  file_name    TEXT, -- the PDF, in the uploads storage
  status       TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'replaced')),
  submitted_at TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX timesheet_submissions_employee ON timesheet_submissions (employee_id, period_start);
ALTER TABLE time_entries ADD COLUMN submission_id INTEGER REFERENCES timesheet_submissions(id) ON DELETE SET NULL;

-- The day pay actually went out. 1099s count payments by the year they were paid.
ALTER TABLE pay_runs ADD COLUMN paid_on TEXT;
UPDATE pay_runs SET paid_on = substr(finalized_at, 1, 10) WHERE status = 'finalized' AND paid_on IS NULL;

-- An officer's W-9 details (who to put on their 1099). The tax ID number is
-- stored scrambled (encrypted); only its last 4 digits are kept readable.
CREATE TABLE tax_profiles (
  employee_id          INTEGER PRIMARY KEY REFERENCES employees(id) ON DELETE CASCADE,
  legal_name           TEXT NOT NULL,
  business_name        TEXT,
  tax_classification   TEXT NOT NULL,
  llc_classification   TEXT,
  address              TEXT NOT NULL,
  city                 TEXT NOT NULL,
  state                TEXT NOT NULL,
  zip                  TEXT NOT NULL,
  tin_type             TEXT NOT NULL CHECK (tin_type IN ('SSN', 'EIN')),
  tin_encrypted        TEXT NOT NULL,
  tin_last4            TEXT NOT NULL,
  backup_withholding   INTEGER NOT NULL DEFAULT 0, -- the IRS told them they're subject to it
  signed_name          TEXT NOT NULL,
  signed_at            TEXT NOT NULL,
  signed_ip            TEXT,
  electronic_consent   INTEGER NOT NULL DEFAULT 0, -- agreed to get their 1099 online instead of on paper
  consent_at           TEXT,
  updated_at           TEXT NOT NULL DEFAULT app_now()
);

-- A 1099-NEC for one person and year. The numbers and names are copied in
-- when it's created, so it doesn't change by itself afterwards.
CREATE TABLE tax_forms (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id       INTEGER NOT NULL REFERENCES employees(id),
  tax_year          INTEGER NOT NULL,
  box1              DOUBLE PRECISION NOT NULL DEFAULT 0, -- nonemployee compensation
  box4              DOUBLE PRECISION NOT NULL DEFAULT 0, -- federal income tax withheld
  box5              DOUBLE PRECISION NOT NULL DEFAULT 0, -- state tax withheld
  box6              TEXT,                                -- state / payer's state number
  box7              DOUBLE PRECISION NOT NULL DEFAULT 0, -- state income
  payer             JSONB NOT NULL,
  recipient         JSONB NOT NULL,
  status            TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'issued')),
  corrected         INTEGER NOT NULL DEFAULT 0,
  released          INTEGER NOT NULL DEFAULT 0, -- the officer can download it in their portal
  issued_at         TEXT,
  created_by        INTEGER REFERENCES users(id),
  created_at        TEXT NOT NULL DEFAULT app_now(),
  UNIQUE (employee_id, tax_year)
);
