-- Emails waiting to go out, and a record of the ones that went. If the mail
-- server is down (or email isn't set up yet), they wait here and are tried again.
CREATE TABLE email_outbox (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  to_address    TEXT NOT NULL,
  subject       TEXT NOT NULL,
  body          TEXT NOT NULL,
  attachments   JSONB NOT NULL DEFAULT '[]', -- [{ "filename": "...", "file": "<stored file name>" }]
  submission_id INTEGER REFERENCES timesheet_submissions(id) ON DELETE CASCADE,
  status        TEXT NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'sending', 'sent', 'failed')),
  attempts      INTEGER NOT NULL DEFAULT 0,
  claimed_at    BIGINT, -- when a sender picked it up (milliseconds), so two senders never send it twice
  last_error    TEXT,
  created_at    TEXT NOT NULL DEFAULT app_now(),
  sent_at       TEXT
);
CREATE INDEX email_outbox_status ON email_outbox (status);
CREATE INDEX email_outbox_submission ON email_outbox (submission_id);
