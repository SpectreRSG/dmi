-- Direct deposit: the bank account each person is paid into. An account an
-- officer adds or changes themselves waits for an admin to approve it (so a
-- stolen login can't redirect someone's pay); one the office types in from a
-- signed paper form is active straight away. The account number is stored
-- encrypted; the routing number is the bank's public number.
CREATE TABLE bank_accounts (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id       INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  status            TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'active', 'replaced')),
  holder_name       TEXT NOT NULL,
  account_type      TEXT NOT NULL CHECK (account_type IN ('checking', 'savings')),
  routing_number    TEXT NOT NULL,
  account_encrypted TEXT NOT NULL,
  account_last4     TEXT NOT NULL,
  consent_at        TEXT NOT NULL, -- agreed to be paid by direct deposit (California: it can't be required)
  entered_by        INTEGER REFERENCES users(id) ON DELETE SET NULL, -- the office typed it in
  approved_by       INTEGER REFERENCES users(id) ON DELETE SET NULL,
  approved_at       TEXT,
  created_at        TEXT NOT NULL DEFAULT app_now()
);
CREATE UNIQUE INDEX bank_accounts_one_active ON bank_accounts (employee_id) WHERE status = 'active';
CREATE UNIQUE INDEX bank_accounts_one_pending ON bank_accounts (employee_id) WHERE status = 'pending';
