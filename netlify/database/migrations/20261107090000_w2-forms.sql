-- Year-end Forms W-2 for W-2 employees, and whether each employee agreed to
-- get theirs online instead of on paper.

-- A W-2 for one employee and year. The numbers, the company's and the
-- employee's details are copied in when it's made, so it doesn't change by
-- itself afterwards. The Social Security number stays encrypted.
CREATE TABLE w2_forms (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id),
  tax_year    INTEGER NOT NULL,
  boxes       JSONB NOT NULL, -- box1 … box17 amounts, box14 lines, box15 state
  employer    JSONB NOT NULL, -- name, EIN, address, state ID number
  employee    JSONB NOT NULL, -- name, address, ssn_encrypted, ssn_last4
  status      TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'issued')),
  released    INTEGER NOT NULL DEFAULT 0, -- the employee can download it in their account
  issued_at   TEXT,
  created_by  INTEGER REFERENCES users(id),
  created_at  TEXT NOT NULL DEFAULT app_now(),
  UNIQUE (employee_id, tax_year)
);

ALTER TABLE withholding_profiles ADD COLUMN electronic_consent INTEGER NOT NULL DEFAULT 0; -- agreed to get their W-2 online
ALTER TABLE withholding_profiles ADD COLUMN consent_at TEXT;
