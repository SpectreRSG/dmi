-- ============================================================================
-- DATABASE TABLES (Postgres, hosted by Netlify Database)
-- Think of each table as a spreadsheet tab: every row is one record, every
-- column is one piece of information about it.
--
-- Netlify applies this file automatically when the site deploys. Never edit it
-- after it has been applied: to change the database, add a NEW migration file
-- next to it with a later number.
-- ============================================================================

-- Company-wide settings such as the company name, time zone and overtime rules.
CREATE TABLE settings (
  key   TEXT PRIMARY KEY,
  value TEXT
);

-- "Now" as text like '2026-10-20 14:30:00', in the company's time zone
-- (from Settings), so every timestamp the database writes matches the app.
CREATE FUNCTION app_now() RETURNS TEXT LANGUAGE sql STABLE AS $$
  SELECT to_char(
    now() AT TIME ZONE COALESCE((SELECT value FROM settings WHERE key = 'timezone'), 'America/Los_Angeles'),
    'YYYY-MM-DD HH24:MI:SS'
  )
$$;

-- People who can log in to this admin website.
CREATE TABLE users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT NOT NULL,
  email         TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL DEFAULT 'manager' CHECK (role IN ('admin', 'manager')),
  active        INTEGER NOT NULL DEFAULT 1,
  last_login_at TEXT,
  created_at    TEXT NOT NULL DEFAULT app_now()
);
CREATE UNIQUE INDEX users_email_unique ON users (lower(email));

-- Login sessions (keeps people signed in between page loads).
CREATE TABLE sessions (
  sid        TEXT PRIMARY KEY,
  data       JSONB NOT NULL,
  expires_at BIGINT NOT NULL
);

-- Recent wrong passwords, used to slow down password guessing.
CREATE TABLE login_attempts (
  key      TEXT PRIMARY KEY,
  count    INTEGER NOT NULL,
  first_at BIGINT NOT NULL
);

-- Guards and other staff members.
CREATE TABLE employees (
  id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name              TEXT NOT NULL,
  last_name               TEXT NOT NULL,
  email                   TEXT,
  phone                   TEXT,
  address                 TEXT,
  position                TEXT,
  employment_type         TEXT,
  hourly_rate             DOUBLE PRECISION NOT NULL DEFAULT 0,
  start_date              TEXT,
  end_date                TEXT,
  license_required        INTEGER NOT NULL DEFAULT 1,
  license_number          TEXT,
  license_expiry          TEXT,
  emergency_contact_name  TEXT,
  emergency_contact_phone TEXT,
  status                  TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  notes                   TEXT,
  created_at              TEXT NOT NULL DEFAULT app_now()
);

-- Customers who hire the firm.
CREATE TABLE clients (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT NOT NULL,
  contact_name  TEXT,
  contact_email TEXT,
  contact_phone TEXT,
  address       TEXT,
  notes         TEXT,
  created_at    TEXT NOT NULL DEFAULT app_now()
);

-- Places where guards work. Each site belongs to one client.
CREATE TABLE sites (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id    INTEGER NOT NULL REFERENCES clients(id),
  name         TEXT NOT NULL,
  address      TEXT,
  instructions TEXT,
  active       INTEGER NOT NULL DEFAULT 1,
  created_at   TEXT NOT NULL DEFAULT app_now()
);

-- Planned work (the roster). employee_id is empty for an unfilled shift.
-- Dates and times are stored as text like '2026-10-20T22:00'.
CREATE TABLE shifts (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id       INTEGER NOT NULL REFERENCES sites(id),
  employee_id   INTEGER REFERENCES employees(id),
  start_at      TEXT NOT NULL,
  end_at        TEXT NOT NULL,
  break_minutes INTEGER NOT NULL DEFAULT 0,
  status        TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'completed', 'cancelled')),
  notes         TEXT,
  created_at    TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX shifts_start ON shifts (start_at);
CREATE INDEX shifts_employee ON shifts (employee_id, start_at);

-- A pay period being prepared (draft) or already paid (finalized).
CREATE TABLE pay_runs (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_start TEXT NOT NULL,
  period_end   TEXT NOT NULL,
  status       TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'finalized')),
  notes        TEXT,
  created_by   INTEGER REFERENCES users(id),
  created_at   TEXT NOT NULL DEFAULT app_now(),
  finalized_at TEXT
);

-- One line per staff member in a pay run (a "copy" of the numbers at the time).
CREATE TABLE pay_run_items (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pay_run_id          INTEGER NOT NULL REFERENCES pay_runs(id) ON DELETE CASCADE,
  employee_id         INTEGER NOT NULL REFERENCES employees(id),
  regular_hours       DOUBLE PRECISION NOT NULL DEFAULT 0,
  overtime_hours      DOUBLE PRECISION NOT NULL DEFAULT 0,
  hourly_rate         DOUBLE PRECISION NOT NULL DEFAULT 0,
  overtime_multiplier DOUBLE PRECISION NOT NULL DEFAULT 1.5,
  regular_pay         DOUBLE PRECISION NOT NULL DEFAULT 0,
  overtime_pay        DOUBLE PRECISION NOT NULL DEFAULT 0,
  adjustment          DOUBLE PRECISION NOT NULL DEFAULT 0,
  adjustment_note     TEXT,
  gross_pay           DOUBLE PRECISION NOT NULL DEFAULT 0
);

-- Hours actually worked (timesheets). They must be approved before they are paid.
CREATE TABLE time_entries (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id   INTEGER NOT NULL REFERENCES employees(id),
  site_id       INTEGER REFERENCES sites(id),
  shift_id      INTEGER REFERENCES shifts(id) ON DELETE SET NULL,
  start_at      TEXT NOT NULL,
  end_at        TEXT NOT NULL,
  break_minutes INTEGER NOT NULL DEFAULT 0,
  status        TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  notes         TEXT,
  approved_by   INTEGER REFERENCES users(id),
  approved_at   TEXT,
  pay_run_id    INTEGER REFERENCES pay_runs(id) ON DELETE SET NULL,
  created_at    TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX time_entries_employee ON time_entries (employee_id, start_at);
CREATE INDEX time_entries_status ON time_entries (status);

-- Contracts and agreements, with clients, staff or anyone else.
CREATE TABLE contracts (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title         TEXT NOT NULL,
  contract_type TEXT NOT NULL,
  party_type    TEXT NOT NULL CHECK (party_type IN ('client', 'employee', 'other')),
  client_id     INTEGER REFERENCES clients(id),
  employee_id   INTEGER REFERENCES employees(id),
  other_party   TEXT,
  status        TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'ended', 'terminated')),
  signed_on     TEXT,
  start_date    TEXT,
  end_date      TEXT,
  value         DOUBLE PRECISION,
  file_name     TEXT,
  file_original TEXT,
  notes         TEXT,
  created_at    TEXT NOT NULL DEFAULT app_now()
);

-- Types of training or certification (e.g. First Aid). validity_months is
-- how long a certificate lasts; leave it empty if it never expires.
CREATE TABLE training_courses (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            TEXT NOT NULL,
  description     TEXT,
  validity_months INTEGER,
  required        INTEGER NOT NULL DEFAULT 0,
  active          INTEGER NOT NULL DEFAULT 1,
  created_at      TEXT NOT NULL DEFAULT app_now()
);
CREATE UNIQUE INDEX training_courses_name_unique ON training_courses (lower(name));

-- Proof that a staff member completed a course.
CREATE TABLE training_records (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id        INTEGER NOT NULL REFERENCES employees(id),
  course_id          INTEGER NOT NULL REFERENCES training_courses(id),
  completed_on       TEXT NOT NULL,
  expires_on         TEXT,
  provider           TEXT,
  certificate_number TEXT,
  file_name          TEXT,
  file_original      TEXT,
  notes              TEXT,
  created_at         TEXT NOT NULL DEFAULT app_now()
);
CREATE INDEX training_records_employee ON training_records (employee_id, course_id);

-- Planned training classes.
CREATE TABLE training_sessions (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  INTEGER NOT NULL REFERENCES training_courses(id),
  starts_at  TEXT NOT NULL,
  location   TEXT,
  trainer    TEXT,
  capacity   INTEGER,
  status     TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'completed', 'cancelled')),
  notes      TEXT,
  created_at TEXT NOT NULL DEFAULT app_now()
);

-- Who is booked into each training class.
CREATE TABLE training_attendees (
  session_id  INTEGER NOT NULL REFERENCES training_sessions(id) ON DELETE CASCADE,
  employee_id INTEGER NOT NULL REFERENCES employees(id),
  attended    INTEGER,
  PRIMARY KEY (session_id, employee_id)
);

-- A history of who did what, for accountability.
CREATE TABLE activity_log (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER REFERENCES users(id),
  action     TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT app_now()
);
